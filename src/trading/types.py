@dataclass
class TradingSignal:
    """Trading signal generated by LLM agents."""
    symbol: str
    signal: str
    conviction: int
    
    entry_price: float
    stop_loss: float
    target_price: float
    trailing_stop_pct: float = 0.0
    
    thesis: str = ""
    key_reasons: List[str] = field(default_factory=list)
    risks: List[str] = field(default_factory=list)
    
    generated_at: datetime = field(default_factory=datetime.now)
    valid_until: datetime = field(default_factory=lambda: datetime.now() + timedelta(days=30))
    last_reviewed: datetime = field(default_factory=datetime.now)
    review_count: int = 0
    review_type: str = "scheduled"
    
    position_open: bool = False
    entry_executed_at: Optional[float] = None
    quantity: int = 0
    highest_price_since_entry: float = 0.0
    
    cap_type: str = "large"
    atr: float = 0.0
    
    previous_derivatives_summary: Optional[str] = None
    
    agent_outputs: Optional[Dict[str, Any]] = None
    full_cio_analysis: str = ""
    
    def to_dict(self) -> Dict[str, Any]:
        """Convert to dictionary for JSON serialization."""
        d = asdict(self)
        d["generated_at"] = self.generated_at.isoformat()
        d["valid_until"] = self.valid_until.isoformat()
        d["last_reviewed"] = self.last_reviewed.isoformat()
        
        if self.agent_outputs is not None:
            d["agent_outputs"] = self._serialize_agent_outputs(self.agent_outputs)
        
        return d
    
    def _serialize_agent_outputs(self, outputs: Dict[str, Any]) -> Dict[str, Any]:
        """Serialize agent outputs for JSON storage."""
        serialized = {}
        for agent_name, output in outputs.items():
            if isinstance(output, dict):
                serialized[agent_name] = {
                    k: v for k, v in output.items()
                    if k in ["status", "verdict", "conviction_score", "thesis", "analysis", "sentiment", "regime", "support_level", "resistance_level"]
                }
            else:
                serialized[agent_name] = str(output)
        return serialized
    
    @classmethod
    def from_dict(cls, d: Dict[str, Any]) -> "TradingSignal":
        """Create from dictionary."""
        d["generated_at"] = datetime.fromisoformat(d["generated_at"])
        d["valid_until"] = datetime.fromisoformat(d["valid_until"])
        d["last_reviewed"] = datetime.fromisoformat(d["last_reviewed"])
        return cls(**d)
    
    def is_expired(self) -> bool:
        """Check if signal is expired."""
        return datetime.now() > self.valid_until
    
    def update_trailing_stop(self, current_price: float, atr: float) -> None:
        """Update trailing stop based on highest price since entry."""
        if current_price > self.highest_price_since_entry:
            self.highest_price_since_entry = current_price
        
        atr_multiplier = self.get_atr_multiplier()
        new_trailing_stop = self.highest_price_since_entry - (atr_multiplier * atr)
        
        if new_trailing_stop > self.trailing_stop_pct:
            self.trailing_stop_pct = new_trailing_stop
    
    def get_atr_multiplier(self) -> float:
        """Get ATR multiplier based on cap type."""
        multipliers = {
            "large": 2.5,
            "mid": 3.0,
            "small": 3.5
        }
        return multipliers.get(self.cap_type, 2.5)
    
    def to_json(self) -> str:
        """Convert to JSON string."""
        return json.dumps(self.to_dict(), indent=2)


@dataclass
class TriggerResult:
    """Result from trigger evaluation."""
